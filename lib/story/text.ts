/* ---------- 한국어 조사 ---------- */
function lastHangul(word: string): string {
  const clean = word.replace(/\*\*/g, "").replace(/\([^)]*\)/g, "").replace(/[「」'"\s]/g, "");
  for (let i = clean.length - 1; i >= 0; i--) {
    const c = clean.charCodeAt(i);
    if (c >= 0xac00 && c <= 0xd7a3) return clean[i];
  }
  return "";
}
const hasBatchim = (word: string) => {
  const ch = lastHangul(word);
  return ch ? (ch.charCodeAt(0) - 0xac00) % 28 !== 0 : false;
};
export const ieyo = (w: string) => w + (hasBatchim(w) ? "이에요" : "예요");
export const eul = (w: string) => w + (hasBatchim(w) ? "을" : "를");
export const iga = (w: string) => w + (hasBatchim(w) ? "이" : "가");
export const eun = (w: string) => w + (hasBatchim(w) ? "은" : "는");
export const wa = (w: string) => w + (hasBatchim(w) ? "과" : "와");

