export function reasonSentence(f: PeriodFlow): string {
  if (f.reasons.length === 0) return "특별히 돕거나 막는 기운 없이, 내가 하는 만큼 흘러가는 무난한 흐름이에요.";
  const parts = f.reasons.map((r, i) => REASON_TEXT[r][i === f.reasons.length - 1 ? 1 : 0]);
  return `그 이유를 풀어보면, ${parts.join(", ")}.`;
}

