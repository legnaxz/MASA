/* ---------- 인연의 글자 (합·충) ---------- */
export function matchLetters(dayStem: string, dayBranch: string) {
  const zodiac = (b: string) => `${BRANCH_KO[b]}(${b}, ${BRANCH_ANIMAL[b].ko}띠)`;
  return {
    stemHap: STEMS.filter((s) => stemHap(s, dayStem) !== null).map((s) => `${STEM_KO[s]}(${s})`),
    hap: BRANCHES.filter((b) => isHap(b, dayBranch)).map(zodiac),
    samhap: BRANCHES.filter((b) => isSamhap(b, dayBranch)).map(zodiac),
    clash: BRANCHES.filter((b) => isClash(b, dayBranch)).map(zodiac),
    wonjin: BRANCHES.filter((b) => isWonjin(b, dayBranch)).map(zodiac),
  };
}
